const OUT_FILE = "/lib/bootstrap/formula-cheatsheet.js";

const TARGETS = [
  "n00dles",
  "foodnstuff",
  "sigma-cosmetics",
  "joesguns",
  "hong-fang-tea",
  "harakiri-sushi",
  "nectar-net",
  "zer0",
  "max-hardware",
  "iron-gym",
];

const LEVELS = [1, 10, 25, 50, 100, 250];

/** @param {NS} ns */
export async function main(ns) {
  ns.disableLog("ALL");

  if (!hasFormulas(ns)) {
    ns.tprint("[BOOTSTRAP] Formulas.exe is required to rebuild the bootstrap cheat sheet.");
    return;
  }

  const player = ns.getPlayer();
  const targets = TARGETS
    .filter(target => ns.serverExists(target))
    .map(target => buildTargetHint(ns, player, target))
    .filter(Boolean)
    .sort((a, b) => b.rank - a.rank);

  const source = renderModule(targets);
  ns.write(OUT_FILE, source, "w");
  ns.tprint(`[BOOTSTRAP] Wrote ${OUT_FILE} with ${targets.length} early-game target hints.`);
}

function hasFormulas(ns) {
  return Boolean(ns.fileExists("Formulas.exe", "home") && ns.formulas?.hacking);
}

function buildTargetHint(ns, basePlayer, target) {
  const server = ns.getServer(target);
  const minHack = Number(ns.getServerRequiredHackingLevel(target)) || 1;
  const maxMoney = Number(ns.getServerMaxMoney(target)) || 0;
  if (maxMoney <= 0) return null;

  const samples = LEVELS.map(level => sampleAtLevel(ns, basePlayer, server, level));
  const bestSample = samples
    .filter(sample => sample.chance > 0)
    .sort((a, b) => b.score - a.score)[0] ?? samples[0];

  const rank = Math.max(1, Math.round(bestSample.score * 1000 + (maxMoney / 1000) + ((Number(ns.getServerGrowth(target)) || 1) * 100) - (minHack * 25)));
  const hackAtMoneyRatio = bestSample.hackPercent > 0.012 ? 0.88 : 0.94;
  const growAtMoneyRatio = bestSample.growThreadsForTwentyFivePercent <= 8 ? 0.72 : 0.82;
  const weakenAtSecurityGap = bestSample.weakenTime < 90_000 ? 4 : 3;

  return {
    name: target,
    rank,
    minHack,
    maxMoney,
    growth: Number(ns.getServerGrowth(target)) || 1,
    minSecurity: Number(ns.getServerMinSecurityLevel(target)) || 1,
    weakenAtSecurityGap,
    growAtMoneyRatio,
    hackAtMoneyRatio,
    samples,
  };
}

function sampleAtLevel(ns, basePlayer, rawServer, level) {
  const player = clonePlayerForLevel(basePlayer, level);
  const server = prepServerForFormula(rawServer);

  const chance = safeNumber(ns.formulas.hacking.hackChance(server, player), 0);
  const hackPercent = safeNumber(ns.formulas.hacking.hackPercent(server, player), 0);
  const weakenTime = safeNumber(ns.formulas.hacking.weakenTime(server, player), ns.getWeakenTime(server.hostname));
  server.moneyAvailable = Math.max(1, server.moneyMax * 0.75);
  const growThreadsForTwentyFivePercent = Math.ceil(safeNumber(
    ns.formulas.hacking.growThreads(server, player, server.moneyMax),
    0,
  ));
  const moneyPerHackThread = server.moneyMax * hackPercent * chance;
  const score = moneyPerHackThread / Math.max(1, weakenTime / 1000);

  return {
    level,
    chance: round(chance, 4),
    hackPercent: round(hackPercent, 5),
    weakenTime: Math.round(weakenTime),
    growThreadsForTwentyFivePercent,
    score: round(score, 2),
  };
}

function clonePlayerForLevel(basePlayer, level) {
  const player = JSON.parse(JSON.stringify(basePlayer));
  player.skills ??= {};
  player.exp ??= {};
  player.mults ??= {};
  player.skills.hacking = level;
  player.exp.hacking = Math.max(1, player.exp.hacking ?? 1);
  return player;
}

function prepServerForFormula(server) {
  const copy = JSON.parse(JSON.stringify(server));
  copy.moneyAvailable = copy.moneyMax;
  copy.hackDifficulty = copy.minDifficulty;
  return copy;
}

function renderModule(targets) {
  const payload = {
    version: "formula-bootstrap-v1",
    generatedAt: Date.now(),
    levels: LEVELS,
    targets,
  };

  return `// Generated by /tools/build-bootstrap-cheatsheet.js while Formulas.exe is available.
export const BOOTSTRAP_FORMULA_CHEATSHEET = ${JSON.stringify(payload, null, 2)};

export function getBootstrapCheatTargetNames() {
  return [...BOOTSTRAP_FORMULA_CHEATSHEET.targets]
    .sort((a, b) => Number(b.rank ?? 0) - Number(a.rank ?? 0))
    .map(target => target.name);
}

export function getBootstrapCheatTarget(name) {
  return BOOTSTRAP_FORMULA_CHEATSHEET.targets.find(target => target.name === name) ?? null;
}
`;
}

function safeNumber(value, fallback) {
  return Number.isFinite(value) ? value : fallback;
}

function round(value, digits) {
  const scale = 10 ** digits;
  return Math.round(value * scale) / scale;
}
